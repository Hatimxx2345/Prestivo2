const dirMap = { fr: "ltr", en: "ltr", ar: "rtl" };
const root = document.documentElement;

function applyLanguage(lang){
  const dict = translations[lang];
  if(!dict) return;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if(dict[key] !== undefined){
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if(dict[key] !== undefined){
      el.setAttribute("placeholder", dict[key]);
    }
  });

  root.setAttribute("lang", lang);
  root.setAttribute("dir", dirMap[lang]);

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  const trigger = document.getElementById("langTrigger");
  if(trigger){
    trigger.querySelector(".lang-current").textContent = lang.toUpperCase();
  }

  localStorage.setItem("prestivo-lang", lang);
}

function initLanguage(){
  const saved = localStorage.getItem("prestivo-lang");
  const browser = (navigator.language || "fr").slice(0,2);
  const lang = saved || (translations[browser] ? browser : "fr");
  applyLanguage(lang);
}

document.getElementById("langSwitch").addEventListener("click", (e) => {
  const btn = e.target.closest(".lang-btn");
  if(btn){
    applyLanguage(btn.dataset.lang);
    closeLangMenu();
    return;
  }
  if(e.target.closest("#langTrigger")){
    toggleLangMenu();
  }
});

function toggleLangMenu(){
  const wrap = document.getElementById("langSwitch");
  const isOpen = wrap.classList.toggle("open");
  document.getElementById("langTrigger").setAttribute("aria-expanded", String(isOpen));
}
function closeLangMenu(){
  const wrap = document.getElementById("langSwitch");
  wrap.classList.remove("open");
  document.getElementById("langTrigger").setAttribute("aria-expanded", "false");
}
document.addEventListener("click", (e) => {
  const wrap = document.getElementById("langSwitch");
  if(wrap.classList.contains("open") && !wrap.contains(e.target)) closeLangMenu();
});
document.addEventListener("keydown", (e) => {
  if(e.key === "Escape") closeLangMenu();
});

function applyTheme(theme){
  root.setAttribute("data-theme", theme);
  localStorage.setItem("prestivo-theme", theme);
}

function initTheme(){
  const saved = localStorage.getItem("prestivo-theme");
  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  applyTheme(saved || (prefersDark ? "dark" : "light"));
}

document.getElementById("themeToggle").addEventListener("click", () => {
  const current = root.getAttribute("data-theme");
  applyTheme(current === "dark" ? "light" : "dark");
});

const menuToggle = document.getElementById("menuToggle");
const mainNav = document.getElementById("mainNav");
menuToggle.addEventListener("click", () => mainNav.classList.toggle("open"));
mainNav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => mainNav.classList.remove("open")));

function selectProduct(name, price){
  const lang = root.getAttribute("lang");
  const banner = document.getElementById("selectedProduct");
  const productField = document.getElementById("fProduct");
  const template = translations[lang]["contact.selectedNote"];

  banner.textContent = template.replace("{product}", name).replace("{price}", price);
  banner.hidden = false;
  if(productField) productField.value = `${name} — ${price}`;

  document.getElementById("contact").scrollIntoView({ behavior: "smooth", block: "start" });
}

document.querySelectorAll(".btn-buy").forEach(btn => {
  btn.addEventListener("click", () => {
    const card = btn.closest(".product-card");
    const name = card.querySelector("h3").textContent.trim();
    const price = card.querySelector(".price").textContent.trim();
    selectProduct(name, price);
  });
});

// Le site et le backend sont maintenant servis ensemble (même domaine),
// donc une simple URL relative suffit — pas besoin de config CORS.
const ORDER_API_URL = "/api/order";

document.getElementById("contactForm").addEventListener("submit", async (e) => {
  e.preventDefault();
  const lang = root.getAttribute("lang");
  const note = document.getElementById("formNote");
  const form = e.target;
  const submitBtn = form.querySelector(".btn-outline");

  const payload = {
    lastname: form.querySelector("#fLastname").value.trim(),
    firstname: form.querySelector("#fFirstname").value.trim(),
    phone: form.querySelector("#fPhone").value.trim(),
    city: form.querySelector("#fCity").value.trim(),
    email: form.querySelector("#fEmail").value.trim(),
    product: form.querySelector("#fProduct").value.trim(),
  };

  if (submitBtn) submitBtn.disabled = true;

  try {
    const res = await fetch(ORDER_API_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });

    if (!res.ok) throw new Error("Erreur serveur");

    const template = translations[lang]["contact.success"];
    note.textContent = template.replace("{name}", payload.firstname || "");
    form.reset();

    const banner = document.getElementById("selectedProduct");
    banner.hidden = true;
    banner.textContent = "";
  } catch (err) {
    console.error("Erreur envoi commande :", err);
    note.textContent =
      lang === "ar"
        ? "حدث خطأ، يرجى المحاولة مرة أخرى."
        : lang === "en"
        ? "Something went wrong, please try again."
        : "Une erreur est survenue, veuillez réessayer.";
  } finally {
    if (submitBtn) submitBtn.disabled = false;
  }
});

function initReveal(){
  const targets = document.querySelectorAll(".reveal, .divider");
  if(!("IntersectionObserver" in window)){
    targets.forEach(t => t.classList.add("is-visible"));
    return;
  }
  const io = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if(entry.isIntersecting){
        entry.target.classList.add("is-visible");
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15, rootMargin: "0px 0px -8% 0px" });
  targets.forEach(t => io.observe(t));
}

function initHeaderShadow(){
  const header = document.querySelector(".site-header");
  if(!header) return;
  const onScroll = () => {
    header.classList.toggle("scrolled", window.scrollY > 12);
  };
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

